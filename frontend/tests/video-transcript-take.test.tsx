import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { act, cleanup, fireEvent, render, screen } from "@testing-library/react";
import type { ReactNode } from "react";
import { type TranscriptHandle, VideoTranscript } from "@/components/video-transcript";
import { addHighlight, type Passage } from "@/lib/highlight";

const { fetchNote, saveNote, updateNote, searchNotes } = vi.hoisted(() => ({
  fetchNote: vi.fn(),
  saveNote: vi.fn(),
  updateNote: vi.fn(),
  searchNotes: vi.fn(),
}));
vi.mock("@/lib/api", () => {
  class ChangedOnDisk extends Error {}
  return { fetchNote, saveNote, updateNote, searchNotes, ChangedOnDisk };
});

const NOTE = "20 Video/Talk.md";
const ID = "dQw4w9WgXcQ";
const TEXT = [
  "## Transcript",
  "",
  "_Captions of `dQw4w9WgXcQ`, in `en`, generated by YouTube._",
  "",
  "[00:05] First paragraph words.",
  "",
  "[00:31] Second paragraph words.",
  "",
  "[01:10] Third paragraph words.",
  "",
].join("\n");
const PASSAGE: Passage = {
  text: "Second paragraph words.",
  chapter: "at 00:31",
  link: `[00:31](https://www.youtube.com/watch?v=${ID}&t=31s)`,
};

/** The pane as the route would draw it, with the take's own query client. */
function renderPane(onTake: (passage: Passage) => Promise<string | null>, second = 10) {
  const handle: { current: TranscriptHandle | null } = { current: null };
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  const wrapper = ({ children }: { children: ReactNode }) => (
    <QueryClientProvider client={client}>{children}</QueryClientProvider>
  );
  render(
    <VideoTranscript
      note={NOTE}
      id={ID}
      text={TEXT}
      second={second}
      archive={false}
      onTake={onTake}
      onSeek={() => {}}
      handle={handle}
    />,
    { wrapper },
  );
  return handle;
}

/** The words of the paragraph at `seconds`, the text node after its time button. */
function wordsAt(seconds: number): Text {
  const node = document.querySelector(`li[data-at="${seconds}"] p`)?.lastChild;
  if (!(node instanceof Text)) throw new Error(`no words at ${seconds}`);
  return node;
}

/** Selects the words of one paragraph, and tells the document so, as a browser does. */
function selectParagraph(seconds: number) {
  const words = wordsAt(seconds);
  document.getSelection()?.setBaseAndExtent(words, 0, words, words.length);
  selectionChanged();
}

function selectionChanged() {
  act(() => {
    document.dispatchEvent(new Event("selectionchange"));
  });
}

afterEach(() => {
  cleanup();
  document.getSelection()?.removeAllRanges();
  vi.resetAllMocks();
});

beforeEach(() => {
  // What the route writes: the anchor line is the time link alone, the chapter stripped.
  fetchNote.mockResolvedValue(
    addHighlight(TEXT, { text: PASSAGE.text, chapter: "", link: PASSAGE.link }, "hl-abcdef"),
  );
  saveNote.mockImplementation(async (path: string, content: string) => ({ path, content }));
  searchNotes.mockResolvedValue([]);
  updateNote.mockResolvedValue(null);
});

describe("the transcript's take", () => {
  it("#791 A8 a selection in a paragraph shows the take button labelled with its time", async () => {
    renderPane(async () => "hl-abcdef");

    selectParagraph(31);

    const button = await screen.findByRole("button", { name: "Take the passage" });
    expect(button.textContent).toContain("at 00:31");
  });

  it("#791 A8 a click on the take button writes the words with their time link and shows the toast with Undo", async () => {
    const onTake = vi.fn(async (_passage: Passage) => "hl-abcdef");
    renderPane(onTake);

    selectParagraph(31);
    fireEvent.click(await screen.findByRole("button", { name: "Take the passage" }));

    expect(onTake.mock.calls[0]?.[0]).toEqual(PASSAGE);
    await screen.findByText("Taken into the video's note");
    expect(screen.queryByRole("button", { name: "Undo" })).not.toBeNull();
  });

  it("#791 A8 the handle's take writes the held selection and answers true", async () => {
    const onTake = vi.fn(async (_passage: Passage) => "hl-abcdef");
    const handle = renderPane(onTake);

    selectParagraph(31);
    await screen.findByRole("button", { name: "Take the passage" });
    let answered = false;
    act(() => {
      answered = handle.current?.take() === true;
    });

    expect({ answered, passage: onTake.mock.calls[0]?.[0] }).toEqual({
      answered: true,
      passage: PASSAGE,
    });
    await screen.findByText("Taken into the video's note");
  });

  it("#791 A8 the handle's take with no selection held answers false and writes nothing", () => {
    const onTake = vi.fn(async (_passage: Passage) => "hl-abcdef");
    const handle = renderPane(onTake);

    let answered = true;
    act(() => {
      answered = handle.current?.take() === true;
    });

    expect({ answered, writes: onTake.mock.calls.length }).toEqual({ answered: false, writes: 0 });
  });

  it("#791 I8 a selection made backwards takes the time of the paragraph it starts in", async () => {
    const onTake = vi.fn(async (_passage: Passage) => "hl-abcdef");
    renderPane(onTake);

    // Anchor in the third paragraph, focus in the second: the range starts in the second.
    const earlier = wordsAt(31);
    const later = wordsAt(70);
    document.getSelection()?.setBaseAndExtent(later, 0, earlier, earlier.length);
    selectionChanged();
    fireEvent.click(await screen.findByRole("button", { name: "Take the passage" }));

    await screen.findByText("Taken into the video's note");
    const passage = onTake.mock.calls[0]?.[0];
    expect({ chapter: passage?.chapter, link: passage?.link }).toEqual({
      chapter: "at 00:31",
      link: PASSAGE.link,
    });
  });

  it("#791 I4 a selection outside the transcript list shows no take button", async () => {
    renderPane(async () => "hl-abcdef");

    selectParagraph(31);
    await screen.findByRole("button", { name: "Take the passage" });

    // The pane's own header, which is outside the list.
    const label = screen.getByText("TRANSCRIPT").firstChild;
    if (!(label instanceof Text)) throw new Error("no label text");
    document.getSelection()?.setBaseAndExtent(label, 0, label, label.length);
    selectionChanged();

    expect(screen.queryByRole("button", { name: "Take the passage" })).toBeNull();
  });
});
