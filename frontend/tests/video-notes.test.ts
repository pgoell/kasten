/**
 * The video's note read back: chapters, transcript paragraphs, the takes that
 * point into the video, and the time links that write them.
 */

import {
  currentAt,
  noteChapters,
  parseTime,
  timeLink,
  transcriptParagraphs,
  videoTakes,
  watchUrl,
} from "@/lib/video-notes";

const ID = "dQw4w9WgXcQ";
const OTHER = "aaaaaaaaaaa";

describe("parseTime", () => {
  it("#791 A2 parseTime reads the stamp shapes and refuses the rest", () => {
    expect({
      bracketed: parseTime("[12:34]"),
      bare: parseTime("12:34"),
      youtube: parseTime("0:00"),
      hours: parseTime("[1:02:03]"),
      oneDigitSeconds: parseTime("1:2"),
      secondsPastMinute: parseTime("12:60"),
      minutesPastHour: parseTime("1:60:00"),
      unpaired: parseTime("[12:34"),
    }).toEqual({
      bracketed: 754,
      bare: 754,
      youtube: 0,
      hours: 3723,
      oneDigitSeconds: null,
      secondsPastMinute: null,
      minutesPastHour: null,
      unpaired: null,
    });
  });
});

describe("noteChapters", () => {
  it("#791 A2 chapters are read under their heading in the note's order, with each marker and separator", () => {
    const note = [
      "# Lecture",
      "",
      "## Chapters",
      "",
      "- [00:00] Intro",
      "* 1:02 - The model",
      "3. [1:02:03] Late chapter",
      "12:34 — Dashes",
      "+ 13:00: Colon",
      "",
      "## Notes",
      "- [05:00] not a chapter",
    ].join("\n");

    expect(noteChapters(note)).toEqual([
      { seconds: 0, text: "Intro" },
      { seconds: 62, text: "The model" },
      { seconds: 3723, text: "Late chapter" },
      { seconds: 754, text: "Dashes" },
      { seconds: 780, text: "Colon" },
    ]);
  });

  it("#791 A2 lines that are not chapters are skipped, and the section ends at the next heading", () => {
    const note = [
      "## Chapters",
      "",
      "Intro without a time",
      "- [00:xx] bad stamp",
      "- 12:34",
      "- [01:00] Real",
      "### Sub",
      "- [02:00] Still in the section",
      "## Next",
      "- [03:00] Outside",
    ].join("\n");

    expect(noteChapters(note)).toEqual([
      { seconds: 60, text: "Real" },
      { seconds: 120, text: "Still in the section" },
    ]);
  });

  it("#791 A2 a note with no chapters heading gives none", () => {
    expect(
      noteChapters("Lecture notes, no headings.\n\n- [00:00] Intro\n- [01:00] Next\n"),
    ).toEqual([]);
  });
});

describe("transcriptParagraphs", () => {
  it("#791 A6 each transcript paragraph becomes its stamp and its words, with the lines joined", () => {
    const note = [
      "# Lecture",
      "",
      "## Transcript",
      "",
      "_Captions of `abc`, in `en`, generated by YouTube._",
      "",
      "[00:05] Systems that tolerate faults",
      "are called fault-tolerant.",
      "",
      "[00:40] Next paragraph.",
      "",
      "## Notes",
      "",
      "[00:50] outside the section",
    ].join("\n");

    expect(transcriptParagraphs(note)).toEqual([
      { seconds: 5, text: "Systems that tolerate faults are called fault-tolerant." },
      { seconds: 40, text: "Next paragraph." },
    ]);
  });

  it("#791 A6 a paragraph with no stamp is skipped, and the transcript ends at the next heading", () => {
    const note = [
      "## Transcript",
      "",
      "Words with no stamp.",
      "",
      "[01:00] Kept.",
      "",
      "# Next",
      "[02:00] Outside.",
    ].join("\n");

    expect(transcriptParagraphs(note)).toEqual([{ seconds: 60, text: "Kept." }]);
  });

  it("#791 A6 a paragraph past the first hour opens on its hours", () => {
    const note = "## Transcript\n\n[1:02:03] Late words.\n";

    expect(transcriptParagraphs(note)).toEqual([{ seconds: 3723, text: "Late words." }]);
  });
});

describe("currentAt", () => {
  it("#791 A6 currentAt is the last item started by the second, and -1 before the first", () => {
    const list = [
      { seconds: 0, text: "a" },
      { seconds: 10, text: "b" },
      { seconds: 20, text: "c" },
    ];

    expect({
      before: currentAt(list, -1),
      atStart: currentAt(list, 0),
      between: currentAt(list, 15),
      exact: currentAt(list, 20),
      past: currentAt(list, 999),
      none: currentAt([], 5),
    }).toEqual({ before: -1, atStart: 0, between: 1, exact: 2, past: 2, none: -1 });
  });
});

describe("watchUrl", () => {
  it("#791 A1 watchUrl is the bare watch address below one second", () => {
    expect([watchUrl(ID, 0), watchUrl(ID, 0.9)]).toEqual([
      `https://www.youtube.com/watch?v=${ID}`,
      `https://www.youtube.com/watch?v=${ID}`,
    ]);
  });

  it("#791 A1 watchUrl floors the seconds into the t parameter", () => {
    expect(watchUrl(ID, 754.9)).toBe(`https://www.youtube.com/watch?v=${ID}&t=754s`);
  });
});

describe("timeLink", () => {
  it("#791 A8 timeLink is the stamp without its brackets, linked to that moment", () => {
    expect(timeLink(ID, 754)).toBe(`[12:34](https://www.youtube.com/watch?v=${ID}&t=754s)`);
  });

  it("#791 A8 timeLink past the first hour shows the hours", () => {
    expect(timeLink(ID, 3723)).toBe(`[1:02:03](https://www.youtube.com/watch?v=${ID}&t=3723s)`);
  });
});

describe("videoTakes", () => {
  it("#791 A5 videoTakes lists this video's takes in the note's order, with their seconds and quotes", () => {
    const note = [
      "# Lecture",
      "",
      "## Highlights",
      "",
      "> First quote.",
      "",
      `${timeLink(ID, 754)} ^hl-000001`,
      "",
      "> Second.",
      ">",
      "> Third.",
      "",
      `[00:00](https://www.youtube.com/watch?v=${ID}) ^hl-000002`,
      "",
    ].join("\n");

    expect(videoTakes(note, ID)).toEqual([
      { id: "hl-000001", seconds: 754, quote: "First quote." },
      { id: "hl-000002", seconds: 0, quote: "Second. Third." },
    ]);
  });

  it("#791 A5 a take of another video is left out", () => {
    const note = ["> A quote.", "", `${timeLink(OTHER, 60)} ^hl-000001`, ""].join("\n");

    expect(videoTakes(note, ID)).toEqual([]);
  });

  it("#791 A5 a highlight with no time link is left out", () => {
    const note = ["> A quote.", "", "Chapter ^hl-000003", ""].join("\n");

    expect(videoTakes(note, ID)).toEqual([]);
  });

  it("#791 A5 a quote with brackets reads back as the book's own words", () => {
    const note = ["> \\[\\[x\\]\\]", "", `${timeLink(ID, 60)} ^hl-000004`, ""].join("\n");

    expect(videoTakes(note, ID)).toEqual([{ id: "hl-000004", seconds: 60, quote: "[[x]]" }]);
  });
});
