import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";

// The colours live in the token file now. These scans keep the old One Dark
// palette and literal hex colours from creeping back into the app.

const SRC = path.resolve(import.meta.dirname, "../src");

function walk(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });
}

/** Source path relative to src, with forward slashes, for the messages. */
function rel(file: string): string {
  return path.relative(SRC, file).split(path.sep).join("/");
}

/**
 * The file with its comments blanked. A `(#355)` in a comment is a valid
 * three-digit hex, and a comment that names a One Dark colour is not a use of it.
 */
function code(file: string): string {
  const text = readFileSync(file, "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
  if (!/\.tsx?$/.test(file)) return text;
  // The lookbehind keeps `https://` and other `//` inside a string from ending the line.
  return text.replace(/(^|[^:'"`\\])\/\/[^\n]*/g, "$1");
}

const files = walk(SRC);

it("no One Dark colour is left in the app", () => {
  // A Tailwind utility on a one-* colour (`text-one-fg`), or the old CSS variable.
  const oneColour =
    /--color-one-[\w-]+|\b[a-z-]+-one-(bg|panel|hover|selection|fg|muted|accent|green|warn|yellow|orange|purple|cyan|cursor|line|well)\b/g;
  const hits = files.flatMap((file) =>
    [...code(file).matchAll(oneColour)].map((m) => `${rel(file)}: ${m[0]}`),
  );
  expect(hits).toEqual([]);
});

it("no editor imports the One Dark theme", () => {
  // This file names the package in its own code, so it is the one file skipped.
  const hits = [...files, ...walk(import.meta.dirname)]
    .filter(
      (file) => file !== import.meta.filename && code(file).includes("@codemirror/theme-one-dark"),
    )
    .map((file) => `${rel(file)}: @codemirror/theme-one-dark`);
  expect(hits).toEqual([]);
});

// Each exemption says why the file keeps its literal colours.
const EXEMPT: Record<string, string> = {
  "styles/kasten-theme.css": "the token file itself, where the colours are defined",
  "styles/lists.css":
    "the lists app at lists.html keeps its own palette; #810 moves it to the tokens",
  "lib/book-backing.ts":
    "#000 and #fff are the white page a book's images were drawn for, not a theme colour",
  "routeTree.gen.ts": "generated by the router, not written by hand",
};

it("no hex colour is left outside the token file", () => {
  // `(?<![\w&\\])` skips `&#...`, `\#` selector escapes and `word#` fragments.
  const hex = /(?<![\w&\\])#[0-9a-fA-F]{3,8}\b/g;
  const hits = files
    .filter((file) => /\.(css|tsx?)$/.test(file) && !(rel(file) in EXEMPT))
    .flatMap((file) => [...code(file).matchAll(hex)].map((m) => `${rel(file)}: ${m[0]}`));
  expect(hits).toEqual([]);
});
